const std = @import("std");

pub const CardCardType = enum {
    creature,
    spell,
    land,
    artifact,
    enchantment,
    planeswalker,
};

pub const CardRarity = enum {
    common,
    uncommon,
    rare,
    mythic_rare,
    legendary,
};

pub const Card = struct {
    id: i64 = 0,
    created_at: []const u8 = "",
    updated_at: []const u8 = "",
    public_id: []const u8 = "",
    name: []const u8 = "",
    card_type: CardCardType = .creature,
    rarity: CardRarity = .common,
    mana_cost: i64 = 0,
    mana_colors: []const u8 = "",
    attack: ?i64 = null,
    defense: ?i64 = null,
    loyalty: ?i64 = null,
    description: []const u8 = "",
    flavor_text: ?[]const u8 = null,
    image_url: ?[]const u8 = null,
    artist_name: ?[]const u8 = null,
    legal_formats: []const u8 = "",
    is_banned: bool = false,
    is_restricted: bool = false,
    power_level: i64 = 1,
    metadata: ?[]const u8 = null,
    total_copies_in_circulation: i64 = 0,
    set_id: i64 = 0,
};

